import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../services/storage_service.dart';
import '../services/player_service.dart';
import '../models/playlist_model.dart';
import '../widgets/collage_cover.dart';
import 'playlist_detail_screen.dart';

class LibraryScreen extends StatelessWidget {
  const LibraryScreen({super.key});

  @override
  Widget build(BuildContext context) {
    return Consumer2<MusicStorageService, PlayerService>(
      builder: (context, storage, player, child) {
        if (storage.isLoading) {
          return const Center(
            child: CircularProgressIndicator(color: Colors.white),
          );
        }

        final likedSongs = storage.likedSongsPlaylist;
        final playlists = storage.playlists;

        return RefreshIndicator(
          color: Colors.white,
          backgroundColor: const Color(0xFF212121),
          onRefresh: () => storage.scanLibrary(),
          child: CustomScrollView(
            physics: const AlwaysScrollableScrollPhysics(),
            slivers: [
              // Grid of Playlists (2 Columns)
              SliverPadding(
                padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 12),
                sliver: SliverGrid(
                  gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
                    crossAxisCount: 2,
                    crossAxisSpacing: 14,
                    mainAxisSpacing: 20,
                    childAspectRatio: 0.52,
                  ),
                  delegate: SliverChildBuilderDelegate(
                    (context, index) {
                      // First item is always "Música que te gustó" (Screenshot 1)
                      if (index == 0) {
                        return _buildPlaylistItem(
                          context,
                          playlist: likedSongs ??
                              Playlist(
                                id: 'liked_songs_auto',
                                name: 'Música que te gustó',
                                folderPath: '',
                                songs: [],
                                isAutoGenerated: true,
                              ),
                          player: player,
                          storage: storage,
                        );
                      }

                      final playlist = playlists[index - 1];
                      return _buildPlaylistItem(
                        context,
                        playlist: playlist,
                        player: player,
                        storage: storage,
                      );
                    },
                    childCount: playlists.length + 1,
                  ),
                ),
              ),

              // Bottom spacing for mini player
              const SliverToBoxAdapter(
                child: SizedBox(height: 80),
              ),
            ],
          ),
        );
      },
    );
  }

  Widget _buildPlaylistItem(
    BuildContext context, {
    required Playlist playlist,
    required PlayerService player,
    required MusicStorageService storage,
  }) {
    return GestureDetector(
      onTap: () {
        Navigator.push(
          context,
          MaterialPageRoute(
            builder: (_) => PlaylistDetailScreen(playlist: playlist),
          ),
        );
      },
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // Square Artwork with 2x2 Collage and Floating Play Button
          AspectRatio(
            aspectRatio: 1.0,
            child: CollageCover(
              playlist: playlist,
              onPlayPressed: () {
                if (playlist.songs.isNotEmpty) {
                  player.playSong(playlist.songs.first, playlist: playlist.songs);
                }
              },
              onMenuPressed: () => _showPlaylistMenu(context, playlist, storage),
            ),
          ),
          const SizedBox(height: 8),

          // Title (supports emojis)
          Text(
            playlist.name,
            maxLines: 1,
            overflow: TextOverflow.ellipsis,
            style: const TextStyle(
              color: Colors.white,
              fontSize: 14.5,
              fontWeight: FontWeight.bold,
              letterSpacing: -0.2,
            ),
          ),
          const SizedBox(height: 3),

          // Subtitle
          Text(
            playlist.subtitle,
            maxLines: 2,
            overflow: TextOverflow.ellipsis,
            style: const TextStyle(
              color: Color(0xFFAAAAAA),
              fontSize: 12.5,
              height: 1.25,
            ),
          ),
        ],
      ),
    );
  }

  void _showPlaylistMenu(
    BuildContext context,
    Playlist playlist,
    MusicStorageService storage,
  ) {
    showModalBottomSheet(
      context: context,
      backgroundColor: const Color(0xFF1E1E1E),
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(16)),
      ),
      builder: (ctx) {
        return SafeArea(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              ListTile(
                leading: const Icon(Icons.play_circle_fill, color: Colors.white),
                title: const Text('Reproducir playlist', style: TextStyle(color: Colors.white)),
                onTap: () {
                  final player = Provider.of<PlayerService>(context, listen: false);
                  if (playlist.songs.isNotEmpty) {
                    player.playSong(playlist.songs.first, playlist: playlist.songs);
                  }
                  Navigator.pop(ctx);
                },
              ),
              ListTile(
                leading: const Icon(Icons.folder_open, color: Colors.white),
                title: const Text('Ubicación de la carpeta', style: TextStyle(color: Colors.white)),
                subtitle: Text(playlist.folderPath, style: const TextStyle(color: Colors.white54, fontSize: 11)),
                onTap: () => Navigator.pop(ctx),
              ),
              ListTile(
                leading: const Icon(Icons.refresh, color: Colors.white),
                title: const Text('Actualizar contenido', style: TextStyle(color: Colors.white)),
                onTap: () {
                  storage.scanLibrary();
                  Navigator.pop(ctx);
                },
              ),
            ],
          ),
        );
      },
    );
  }
}
