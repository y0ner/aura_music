import 'dart:typed_data';
import 'song_model.dart';

class Playlist {
  final String id;
  final String name;
  final String folderPath;
  final List<Song> songs;
  final bool isAutoGenerated;
  final String author;

  Playlist({
    required this.id,
    required this.name,
    required this.folderPath,
    required this.songs,
    this.isAutoGenerated = false,
    this.author = 'Yoner Isaza',
  });

  int get trackCount => songs.length;

  String get subtitle {
    if (isAutoGenerated) {
      return '📌 Playlist autogenerada';
    }
    final pistaWord = trackCount == 1 ? 'pista' : 'pistas';
    return 'Playlist • $author • $trackCount $pistaWord';
  }

  /// Extracts up to 4 distinct album artworks from songs for the 2x2 collage
  List<Uint8List> get collageArtworks {
    final List<Uint8List> covers = [];
    for (final song in songs) {
      if (song.artworkBytes != null && song.artworkBytes!.isNotEmpty) {
        covers.add(song.artworkBytes!);
        if (covers.length == 4) break;
      }
    }
    return covers;
  }
}
