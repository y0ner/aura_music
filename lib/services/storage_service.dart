  /// Initialize and scan the music root directory
  Future<void> initialize() async {
    _isLoading = true;
    _statusMessage = 'Iniciando biblioteca de música...';
    notifyListeners();

    await _requestPermissions();
    await _resolveRootMusicDirectory();
    await _stateStore.load();
    await scanLibrary();
  }

  Future<void> _requestPermissions() async {
    if (!Platform.isAndroid) return;
    // READ_MEDIA_AUDIO (Android 13+) basta para leer Music/AuraMusic. Los
    // permisos se piden con la app YA visible (initialize corre post-frame):
    // lanzarlos antes de runApp hace que MIUI/HyperOS deje el diálogo pegado
    // como activity invisible y la pantalla quede en negro.
    // «Todos los archivos» (manageExternalStorage) NO se pide automáticamente:
    // abre Ajustes y saca al usuario de la app; puede concederse a mano si la
    // música vive fuera de Music/.
    try {
      if (await Permission.audio.isDenied) {
        await Permission.audio.request();
      }
    } catch (e) {
      debugPrint('Error pidiendo permiso de audio: $e');
    }
  }

  /// Carpeta raíz alternativa solo para compilar capturas de demostración
  /// (`--dart-define=AURA_DEMO_ROOT=Music/AuraDemo`). La APK publicada no la
  /// define y usa siempre Music/AuraMusic.
  static const String _demoRoot = String.fromEnvironment('AURA_DEMO_ROOT');

  Future<void> _resolveRootMusicDirectory() async {
    try {
      if (Platform.isAndroid) {
        // Try public Music/AuraMusic folder
        final primaryPublic = Directory(
          _demoRoot.isEmpty
              ? '/storage/emulated/0/Music/AuraMusic'
              : '/storage/emulated/0/$_demoRoot',
        );
        if (await primaryPublic.exists()) {
          _rootMusicDirectory = primaryPublic;
          return;
        }
        try {
          await primaryPublic.create(recursive: true);
          _rootMusicDirectory = primaryPublic;
          return;
        } catch (e) {
          debugPrint('No se pudo crear carpeta pública AuraMusic: $e');
        }

        // Fallback to app external storage
        final extDir = await getExternalStorageDirectory();
        if (extDir != null) {
          final fallbackDir = Directory('${extDir.path}/AuraMusic');
          if (!await fallbackDir.exists()) {
            await fallbackDir.create(recursive: true);
          }
          _rootMusicDirectory = fallbackDir;
          return;
        }
      } else if (Platform.isLinux || Platform.isMacOS || Platform.isWindows) {
        // Use ~/Music/AuraMusic on desktop
        final home = Platform.environment['HOME'] ?? '';
        final musicDir = Directory('$home/Music/AuraMusic');
        if (!await musicDir.exists()) {
          await musicDir.create(recursive: true);
        }
        _rootMusicDirectory = musicDir;
        return;
      }

      // Final fallback
      final docDir = await getApplicationDocumentsDirectory();
      final defaultDir = Directory('${docDir.path}/AuraMusic');
      if (!await defaultDir.exists()) {
        await defaultDir.create(recursive: true);
      }
      _rootMusicDirectory = defaultDir;
    } catch (e) {
      debugPrint('Error resolving music directory: $e');
    }
  }

  /// Change the root folder to any user selected folder
  Future<void> setCustomRootDirectory(String path) async {
    final dir = Directory(path);
    if (await dir.exists()) {
      _rootMusicDirectory = dir;
      await scanLibrary();
    }
  }

  /// Creates a new subfolder which instantly becomes a playlist with name & emoji
  Future<Playlist?> createPlaylistFolder(String nameWithEmoji) async {
    if (_rootMusicDirectory == null) return null;
    final sanitized = nameWithEmoji.trim();
    if (sanitized.isEmpty) return null;

    final newDir = Directory('${_rootMusicDirectory!.path}/$sanitized');
    if (!await newDir.exists()) {
      await newDir.create(recursive: true);
    }
    await scanLibrary();
    try {
      return _playlists.firstWhere((p) => p.folderPath == newDir.path);
    } catch (_) {
      return null;
    }
  }

  /// Elimina la carpeta del álbum/playlist con TODO su contenido (canciones,
  /// carátulas, letras). También detiene la reproducción si la canción que
  /// suena pertenecía a esa carpeta.
  Future<bool> deletePlaylistFolder(Playlist playlist) async {
    if (playlist.isAutoGenerated) {
      return false; // "Música que te gustó" no se borra
    }
    if (playlist.id == 'liked_songs_auto') return false;

    final dir = Directory(playlist.folderPath);
    // Seguridad: nunca borrar fuera de la carpeta raíz de música de la app.
    final rootPath = _rootMusicDirectory?.path ?? '';
    if (rootPath.isEmpty ||
        !dir.existsSync() ||
        !dir.path.startsWith(rootPath)) {
      return false;
    }

    try {
      await dir.delete(recursive: true);
      await scanLibrary();
      return true;
    } catch (e) {
      debugPrint('Error eliminando la carpeta de la playlist: $e');
      return false;
    }
  }

  /// Elimina el archivo de audio de una canción (y su .lrc / carátula si
  /// existen). Devuelve true si el archivo se borró del disco.
  Future<bool> deleteSongFile(Song song) async {
    final file = File(song.filePath);
    final rootPath = _rootMusicDirectory?.path ?? '';
    if (rootPath.isEmpty ||
        !file.existsSync() ||
        !file.path.startsWith(rootPath)) {
      return false;
    }

    try {
      await file.delete();
      //.archivos asociados generados por descargas o rippers
      final base = file.path.substring(0, file.path.lastIndexOf('.'));
      for (final ext in ['.jpg', '.lrc', '_private.lrc']) {
        final sidecar = File('$base$ext');
        if (sidecar.existsSync()) {
          try {
            await sidecar.delete();
          } catch (e) {
            debugPrint(
              'Error eliminando archivo asociado ${sidecar.path}: $e',
            );
          }
        }
      }
      final videoId = videoIdFromPath(file.path);
      if (videoId != null) {
        try {
          final dir = await _artworkDirectory();
          final privateCover = artworkFileFor(dir, videoId);
          if (await privateCover.exists()) {
            await privateCover.delete();
          }
        } catch (e) {
          debugPrint('Error eliminando carátula privada: $e');
        }
      }
      try {
        await LyricsService.shared.deleteCachedFor(file.path);
      } catch (e) {
        debugPrint('Error eliminando letra privada en caché: $e');
      }
      await scanLibrary();
      return true;
    } catch (e) {
      debugPrint('Error eliminando la canción: $e');
      return false;
    }
  }

  /// Rescan the directory and subfolders
  Future<void> scanLibrary() => _scan();

  /// Escanea la carpeta raíz. Con [quiet] no muestra el estado de carga
  /// (se usa para refrescar tras recuperar carátulas sin parpadeo).
  Future<void> _scan({bool quiet = false}) async {
    if (_rootMusicDirectory == null) return;
    final watch = Stopwatch()..start();
    if (!quiet) {
      _isLoading = true;
      _statusMessage = 'Escaneando carpetas de música...';
      notifyListeners();
    }

    try {
      if (!_stateStore.isLoaded && !_stateStore.hasInMemoryMutations) {
        await _stateStore.load();
      }

      Directory? artworkDir;
      try {
        artworkDir = await _artworkDirectory();
      } catch (e) {
        debugPrint('Error resolviendo directorio de carátulas: $e');
      }
      if (artworkDir != null) {
        // Quita las franjas negras de las miniaturas de YouTube guardadas
        // antes del rediseño. Cada archivo se procesa una sola vez.
        final cropped = await normalizeArtworkDirectory(artworkDir);
        if (cropped > 0) debugPrint('aura: $cropped carátulas recortadas');
      }

      final List<Playlist> foundPlaylists = [];
      final List<Song> foundAllSongs = [];

      final entities = _rootMusicDirectory!.listSync();

      // Scan subfolders (each is a Playlist)
      for (final entity in entities) {
        if (entity is Directory) {
          final folderName = entity.uri.pathSegments
              .where((s) => s.isNotEmpty)
              .last;

          // Scan audio files inside this subfolder
          final songsInFolder = await _scanSongsInDirectory(
            entity,
            folderName,
            artworkDir,
          );
          foundAllSongs.addAll(songsInFolder);

          foundPlaylists.add(
            Playlist(
              id: entity.path,
              name: folderName,
              folderPath: entity.path,
              songs: songsInFolder,
            ),
          );
        }
      }

      // Also scan root directory directly for loose songs
      final looseSongs = await _scanSongsInDirectory(
        _rootMusicDirectory!,
        'General',
        artworkDir,
      );
      for (final s in looseSongs) {
        if (!foundAllSongs.any((existing) => existing.filePath == s.filePath)) {
          foundAllSongs.add(s);
        }
      }

      _playlists = foundPlaylists;
      _allSongs = foundAllSongs;
      _statusMessage = '';
      _maybeRecoverCovers(artworkDir);
    } catch (e) {
      debugPrint('Error scanning music library: $e');
      _statusMessage = 'Error al escanear: $e';
    } finally {
      _isLoading = false;
      debugPrint(
        'aura: escaneo de ${_allSongs.length} canciones en '
        '${watch.elapsedMilliseconds} ms',
      );
      notifyListeners();
    }
  }

  /// Una vez por sesión: si hay canciones de YouTube (`Título [id].m4a`) sin
  /// carátula, las vuelve a bajar en segundo plano y refresca la biblioteca.
  void _maybeRecoverCovers(Directory? artworkDir) {
    final recoverer = _coverRecoverer;
    if (recoverer == null || artworkDir == null || _coverRecoveryStarted) {
      return;
    }
    final ids = <String>{};
    for (final song in _allSongs) {
      if (song.artworkBytes != null) continue;
      final id = videoIdFromPath(song.filePath);
      if (id != null) ids.add(id);
    }
    if (ids.isEmpty) return;
    _coverRecoveryStarted = true;
    unawaited(() async {
      final recovered = await recoverer(artworkDir, ids);
      if (recovered > 0 && !_disposed) {
        debugPrint('aura: $recovered carátulas recuperadas');
        await _scan(quiet: true);
      }
    }());
  }

  Future<List<Song>> _scanSongsInDirectory(
    Directory dir,
    String defaultCategory, [
    Directory? artworkDir,
  ]) async {
    final List<Song> songs = [];
    final validExtensions = [
      '.mp3',
      '.m4a',
      '.webm',
      '.wav',
      '.flac',
      '.aac',
      '.ogg',
    ];

    final paths = <String>[];
    try {
      final files = await dir.list(followLinks: false).toList();
      for (final file in files) {
        if (file is File) {
          final dotIndex = file.path.lastIndexOf('.');
          if (dotIndex < 0) continue;
          final ext = file.path.toLowerCase().substring(dotIndex);
          if (validExtensions.contains(ext)) paths.add(file.path);
        }
      }
    } catch (e) {
      debugPrint('Error reading files in ${dir.path}: $e');
    }
    if (paths.isEmpty) return songs;

    // Leer etiquetas y carátulas es trabajo síncrono y pesado: se hace en
    // otro isolate para que la interfaz no se congele durante el escaneo.
    try {
      songs.addAll(
        await _parseInBackground(paths, defaultCategory, artworkDir?.path),
      );
      // Los favoritos viven en el store de este isolate: se aplican al volver.
      for (final song in songs) {
        song.isFavorite = _stateStore.isFavorite(
          LibraryStateStore.keyForPath(song.filePath),
        );
      }
    } catch (e) {
      debugPrint('Error escaneando ${dir.path} en segundo plano: $e');
    }
    return songs;
  }

  /// Lee todas las canciones de [paths] (se ejecuta dentro de `Isolate.run`).
  static Future<List<Song>> _parseAudioFiles(
    List<String> paths,
    String category,
    String? artworkDirPath,
  ) async {
    final artworkDir = artworkDirPath == null
        ? null
        : Directory(artworkDirPath);
    final songs = <Song>[];
    for (final path in paths) {
      songs.add(await _parseAudioFile(File(path), category, artworkDir));
    }
    return songs;
  }

  static Future<Song> _parseAudioFile(
    File file,
    String category, [
    Directory? artworkDir,
  ]) async {
    final fileName = file.uri.pathSegments.last;
    // El nombre del archivo es el respaldo si la etiqueta no existe o viene
    // corrupta (los MP3 descargados a veces traen tags ilegibles).
    final fileTitle = MetadataTextFixer.titleFromFileName(fileName);
    String title = fileTitle;
    String artist = Song.unknownArtist;
    String album = category;
    Duration duration = const Duration(minutes: 3, seconds: 45);
    Uint8List? artwork;
    bool hasTagArtist = false;

    DateTime? addedAt;
    try {
      addedAt = await file.lastModified();
    } catch (e) {
      debugPrint('Error leyendo fecha de modificación de ${file.path}: $e');
    }

    try {
      final metadata = readMetadata(file, getImage: true);
      // Los tags ID3 UTF-16 big-endian llegan decodificados como chino
      // (mojibake). MetadataTextFixer los repara y valida el texto.
      final fixedTitle = MetadataTextFixer.cleanTitle(metadata.title);
      final fixedArtist = MetadataTextFixer.cleanTagText(metadata.artist);
      final fixedAlbum = MetadataTextFixer.cleanTagText(metadata.album);
      if (fixedTitle != null && fixedTitle.trim().isNotEmpty) {
        title = fixedTitle.trim();
      }
      if (fixedArtist != null &&
          fixedArtist.trim().isNotEmpty &&
          fixedArtist.trim() != Song.unknownArtist) {
        artist = fixedArtist.trim();
        hasTagArtist = true;
      }
      if (fixedAlbum != null && fixedAlbum.trim().isNotEmpty) {
        album = fixedAlbum.trim();
      }
      if (metadata.duration != null && metadata.duration!.inSeconds > 0) {
        duration = metadata.duration!;
      }
      if (metadata.pictures.isNotEmpty) {
        artwork = metadata.pictures.first.bytes;
      }
    } catch (e) {
      debugPrint('Error leyendo metadatos de ${file.path}: $e');
    }

    if (!hasTagArtist) {
      final parsed = MetadataTextFixer.splitArtistTitle(title);
      title = parsed.title;
      if (parsed.artist != null) {
        artist = parsed.artist!;
      }
    }

    final bool isExplicit =
        title.toLowerCase().contains('remix') ||
        title.toLowerCase().contains('malandro') ||
        title.toLowerCase().contains('shit') ||
        category.toLowerCase().contains('trap');

    if (artwork == null) {
      final baseWithoutExt = file.path.substring(0, file.path.lastIndexOf('.'));
      final coverFile = File('$baseWithoutExt.jpg');
      if (coverFile.existsSync()) {
        try {
          artwork = coverFile.readAsBytesSync();
        } catch (e) {
          debugPrint('Error leyendo carátula local ${coverFile.path}: $e');
        }
      }
    }

    if (artwork == null && artworkDir != null) {
      final videoId = videoIdFromPath(file.path);
      if (videoId != null) {
        final privateCover = artworkFileFor(artworkDir, videoId);
        if (privateCover.existsSync()) {
          try {
            artwork = privateCover.readAsBytesSync();
          } catch (e) {
            debugPrint('Error leyendo carátula privada: $e');
          }
        }
      }
    }

    return Song(
      id: file.path,
      title: title,
      artist: artist,
      album: album,
      filePath: file.path,
      duration: duration,
      artworkBytes: artwork,
      isExplicit: isExplicit,
      category: category,
      addedAt: addedAt,
    );
  }

  Future<void> toggleFavorite(Song song) {
    song.isFavorite = !song.isFavorite;
    final key = LibraryStateStore.keyFor(song);
    for (final item in _allSongs) {
      if (!identical(item, song) && LibraryStateStore.keyFor(item) == key) {
        item.isFavorite = song.isFavorite;
      }
    }
    final pending = _stateStore.setFavorite(key, song.isFavorite);
    notifyListeners();
    return pending;
  }

  void recordPlay(Song song) {
    unawaited(_stateStore.recordPlay(LibraryStateStore.keyFor(song)));
    notifyListeners();
  }

  int _compareByLastPlayedDesc(Song a, Song b) {
    final keyA = LibraryStateStore.keyFor(a);
    final keyB = LibraryStateStore.keyFor(b);
    final timeA = _stateStore.lastPlayed(keyA);
    final timeB = _stateStore.lastPlayed(keyB);
    if (timeA != null && timeB != null) {
      final timeCmp = timeB.compareTo(timeA);
      if (timeCmp != 0) return timeCmp;
    } else if (timeA != null || timeB != null) {
      return timeB != null ? 1 : -1;
    }
    return _stateStore.playSequence(keyB).compareTo(
      _stateStore.playSequence(keyA),
    );
  }

  List<Song> get recentlyPlayed =>
      _memo('recentlyPlayed', _computeRecentlyPlayed);

  /// La misma canción puede estar en dos carpetas (mismo id de video): en las
  /// listas derivadas se muestra una sola vez, la primera según el orden.
  static Iterable<Song> _uniqueByKey(Iterable<Song> songs) sync* {
    final seen = <String>{};
    for (final song in songs) {
      if (seen.add(LibraryStateStore.keyFor(song))) yield song;
    }
  }

  List<Song> _computeRecentlyPlayed() {
    final items = _allSongs
        .where(
          (song) =>
              _stateStore.lastPlayed(LibraryStateStore.keyFor(song)) != null,
        )
        .toList();
    items.sort(_compareByLastPlayedDesc);
    return _uniqueByKey(items).take(_maxDerivedSongs).toList();
  }

  List<Song> get mostPlayed => _memo('mostPlayed', _computeMostPlayed);

  List<Song> _computeMostPlayed() {
    final items = _allSongs
        .where(
          (song) => _stateStore.playCount(LibraryStateStore.keyFor(song)) >= 1,
        )
        .toList();
    items.sort((a, b) {
      final countA = _stateStore.playCount(LibraryStateStore.keyFor(a));
      final countB = _stateStore.playCount(LibraryStateStore.keyFor(b));
      final countCmp = countB.compareTo(countA);
      if (countCmp != 0) return countCmp;
      return _compareByLastPlayedDesc(a, b);
    });
    return _uniqueByKey(items).take(_maxDerivedSongs).toList();
  }

  List<Song> get recentlyAdded =>
      _memo('recentlyAdded', _computeRecentlyAdded);

  List<Song> _computeRecentlyAdded() {
    final items = List<Song>.from(_allSongs);
    items.sort((a, b) {
      final addedA = a.addedAt;
      final addedB = b.addedAt;
      if (addedA != null && addedB != null) {
        return addedB.compareTo(addedA);
      }
      if (addedA != null || addedB != null) {
        return addedB != null ? 1 : -1;
      }
      return 0;
    });
    return _uniqueByKey(items).take(_maxDerivedSongs).toList();
  }

  Playlist? autoPlaylist(AutoPlaylistKind kind) =>
      _memo(('autoPlaylist', kind), () => _computeAutoPlaylist(kind));

  Playlist? _computeAutoPlaylist(AutoPlaylistKind kind) {
    final ({String id, String name, List<Song> songs}) spec = switch (kind) {
      AutoPlaylistKind.recentlyAdded => (
        id: 'auto_recently_added',
        name: 'Recién añadidas',
        songs: recentlyAdded,
      ),
      AutoPlaylistKind.mostPlayed => (
        id: 'auto_most_played',
        name: 'Más escuchadas',
        songs: mostPlayed,
      ),
      AutoPlaylistKind.recentlyPlayed => (
        id: 'auto_recently_played',
        name: 'Escuchado hace poco',
        songs: recentlyPlayed,
      ),
    };
    if (spec.songs.isEmpty) return null;
    return Playlist(
      id: spec.id,
      name: spec.name,
      folderPath: _rootMusicDirectory?.path ?? '',
      songs: spec.songs,
      isAutoGenerated: true,
    );
  }

  static String _normalizeSearchText(String text) {
    final withoutMarks = text.toLowerCase().replaceAll(
      RegExp(r'[\u0300-\u036f]'),
      '',
    );
    final buffer = StringBuffer();
    for (var i = 0; i < withoutMarks.length; i++) {
      final ch = withoutMarks[i];
      buffer.write(_accentMap[ch] ?? ch);
    }
    return buffer.toString();
  }

  List<Song> searchSongs(String query) {
    final q = _normalizeSearchText(query.trim());
    if (q.isEmpty) return const [];

    final startsWithTitle = <Song>[];
    final startsWithOther = <Song>[];
    final containsMatch = <Song>[];

    for (final song in _allSongs) {
      final normTitle = _normalizeSearchText(song.title);
      final normArtist = song.hasKnownArtist
          ? _normalizeSearchText(song.artist)
          : '';
      final normCategory = _normalizeSearchText(song.category);

      if (normTitle.startsWith(q)) {
        startsWithTitle.add(song);
      } else if ((normArtist.isNotEmpty && normArtist.startsWith(q)) ||
          normCategory.startsWith(q)) {
        startsWithOther.add(song);
      } else if (normTitle.contains(q) ||
          (normArtist.isNotEmpty && normArtist.contains(q)) ||
          normCategory.contains(q)) {
        containsMatch.add(song);
      }
    }

    return [...startsWithTitle, ...startsWithOther, ...containsMatch];
  }

  List<Playlist> searchPlaylists(String query) {
    final q = _normalizeSearchText(query.trim());
    if (q.isEmpty) return const [];

    final startsWithMatch = <Playlist>[];
    final containsMatch = <Playlist>[];

    for (final playlist in _playlists) {
      final normName = _normalizeSearchText(playlist.name);
      if (normName.startsWith(q)) {
        startsWithMatch.add(playlist);
      } else if (normName.contains(q)) {
        containsMatch.add(playlist);
      }
    }

    return [...startsWithMatch, ...containsMatch];
  }

