import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:path_provider/path_provider.dart';
import 'package:permission_handler/permission_handler.dart';
import 'package:audio_metadata_reader/audio_metadata_reader.dart';

import '../models/song_model.dart';
import '../models/playlist_model.dart';
import '../utils/metadata_text_fixer.dart';
import 'artwork_store.dart';

class MusicStorageService extends ChangeNotifier {
  final DirectoryProvider _artworkDirectory;
  Directory? _rootMusicDirectory;
  List<Playlist> _playlists = [];
  List<Song> _allSongs = [];
  bool _isLoading = false;
  String _statusMessage = '';

  MusicStorageService({DirectoryProvider? artworkDirectory})
      : _artworkDirectory = artworkDirectory ?? defaultArtworkDirectory;

  Directory? get rootMusicDirectory => _rootMusicDirectory;
  List<Playlist> get playlists => _playlists;
  List<Song> get allSongs => _allSongs;
  bool get isLoading => _isLoading;
  String get statusMessage => _statusMessage;

  Playlist? get likedSongsPlaylist {
    final liked = _allSongs.where((s) => s.isFavorite).toList();
    return Playlist(
      id: 'liked_songs_auto',
      name: 'Música que te gustó',
      folderPath: _rootMusicDirectory?.path ?? '',
      songs: liked,
      isAutoGenerated: true,
      author: 'Yoner Isaza',
    );
  }

  /// Initialize and scan the music root directory
  Future<void> initialize() async {
    _isLoading = true;
    _statusMessage = 'Iniciando biblioteca de música...';
    notifyListeners();

    await _requestPermissions();
    await _resolveRootMusicDirectory();
    await scanLibrary();
  }

  Future<void> _requestPermissions() async {
    if (!Platform.isAndroid) return;
    // READ_MEDIA_AUDIO (Android 13+) basta para leer Music/AuraMusic. Los
    // permisos se piden con la app YA visible (initialize corre post-frame):
    // lanzarlos antes de runApp hace que MIUI/HyperOS deje el diálogo pegado
    // como activity invisible y la pantalla quede en negro.
    // «Todos los archivos» (manageExternalStorage) NO se pide automáticamente:
    // abre Ajustes y saca al usuario de la app; puede concederse a mano si la
    // música vive fuera de Music/.
    try {
      if (await Permission.audio.isDenied) {
        await Permission.audio.request();
      }
    } catch (e) {
      debugPrint('Error pidiendo permiso de audio: $e');
    }
  }

  Future<void> _resolveRootMusicDirectory() async {
    try {
      if (Platform.isAndroid) {
        // Try public Music/AuraMusic folder
        final primaryPublic = Directory('/storage/emulated/0/Music/AuraMusic');
        if (await primaryPublic.exists()) {
          _rootMusicDirectory = primaryPublic;
          return;
        }
        try {
          await primaryPublic.create(recursive: true);
          _rootMusicDirectory = primaryPublic;
          return;
        } catch (_) {}

        // Fallback to app external storage
        final extDir = await getExternalStorageDirectory();
        if (extDir != null) {
          final fallbackDir = Directory('${extDir.path}/AuraMusic');
          if (!await fallbackDir.exists()) {
            await fallbackDir.create(recursive: true);
          }
          _rootMusicDirectory = fallbackDir;
          return;
        }
      } else if (Platform.isLinux || Platform.isMacOS || Platform.isWindows) {
        // Use ~/Music/AuraMusic on desktop
        final home = Platform.environment['HOME'] ?? '';
        final musicDir = Directory('$home/Music/AuraMusic');
        if (!await musicDir.exists()) {
          await musicDir.create(recursive: true);
        }
        _rootMusicDirectory = musicDir;
        return;
      }

      // Final fallback
      final docDir = await getApplicationDocumentsDirectory();
      final defaultDir = Directory('${docDir.path}/AuraMusic');
      if (!await defaultDir.exists()) {
        await defaultDir.create(recursive: true);
      }
      _rootMusicDirectory = defaultDir;
    } catch (e) {
      debugPrint('Error resolving music directory: $e');
    }
  }

  /// Change the root folder to any user selected folder
  Future<void> setCustomRootDirectory(String path) async {
    final dir = Directory(path);
    if (await dir.exists()) {
      _rootMusicDirectory = dir;
      await scanLibrary();
    }
  }

  /// Creates a new subfolder which instantly becomes a playlist with name & emoji
  Future<Playlist?> createPlaylistFolder(String nameWithEmoji) async {
    if (_rootMusicDirectory == null) return null;
    final sanitized = nameWithEmoji.trim();
    if (sanitized.isEmpty) return null;

    final newDir = Directory('${_rootMusicDirectory!.path}/$sanitized');
    if (!await newDir.exists()) {
      await newDir.create(recursive: true);
    }
    await scanLibrary();
    try {
      return _playlists.firstWhere((p) => p.folderPath == newDir.path);
    } catch (_) {
      return null;
    }
  }

  /// Elimina la carpeta del álbum/playlist con TODO su contenido (canciones,
  /// carátulas, letras). También detiene la reproducción si la canción que
  /// suena pertenecía a esa carpeta.
  Future<bool> deletePlaylistFolder(Playlist playlist) async {
    if (playlist.isAutoGenerated) {
      return false; // "Música que te gustó" no se borra
    }
    if (playlist.id == 'liked_songs_auto') return false;

    final dir = Directory(playlist.folderPath);
    // Seguridad: nunca borrar fuera de la carpeta raíz de música de la app.
    final rootPath = _rootMusicDirectory?.path ?? '';
    if (rootPath.isEmpty ||
        !dir.existsSync() ||
        !dir.path.startsWith(rootPath)) {
      return false;
    }

    try {
      await dir.delete(recursive: true);
      await scanLibrary();
      return true;
    } catch (e) {
      debugPrint('Error eliminando la carpeta de la playlist: $e');
      return false;
    }
  }

  /// Elimina el archivo de audio de una canción (y su .lrc / carátula si
  /// existen). Devuelve true si el archivo se borró del disco.
  Future<bool> deleteSongFile(Song song) async {
    final file = File(song.filePath);
    final rootPath = _rootMusicDirectory?.path ?? '';
    if (rootPath.isEmpty ||
        !file.existsSync() ||
        !file.path.startsWith(rootPath)) {
      return false;
    }

    try {
      await file.delete();
      //.archivos asociados generados por descargas o rippers
      final base = file.path.substring(0, file.path.lastIndexOf('.'));
      for (final ext in ['.jpg', '.lrc', '_private.lrc']) {
        final sidecar = File('$base$ext');
        if (sidecar.existsSync()) {
          try {
            await sidecar.delete();
          } catch (_) {}
        }
      }
      final videoId = videoIdFromPath(file.path);
      if (videoId != null) {
        try {
          final dir = await _artworkDirectory();
          final privateCover = artworkFileFor(dir, videoId);
          if (await privateCover.exists()) {
            await privateCover.delete();
          }
        } catch (e) {
          debugPrint('Error eliminando carátula privada: $e');
        }
      }
      await scanLibrary();
      return true;
    } catch (e) {
      debugPrint('Error eliminando la canción: $e');
      return false;
    }
  }

  /// Rescan the directory and subfolders
  Future<void> scanLibrary() async {
    if (_rootMusicDirectory == null) return;
    _isLoading = true;
    _statusMessage = 'Escaneando carpetas de música...';
    notifyListeners();

    try {
      Directory? artworkDir;
      try {
        artworkDir = await _artworkDirectory();
      } catch (e) {
        debugPrint('Error resolviendo directorio de carátulas: $e');
      }

      final List<Playlist> foundPlaylists = [];
      final List<Song> foundAllSongs = [];

      final entities = _rootMusicDirectory!.listSync();

      // Scan subfolders (each is a Playlist)
      for (final entity in entities) {
        if (entity is Directory) {
          final folderName = entity.uri.pathSegments
              .where((s) => s.isNotEmpty)
              .last;

          // Scan audio files inside this subfolder
          final songsInFolder = await _scanSongsInDirectory(
            entity,
            folderName,
            artworkDir,
          );
          foundAllSongs.addAll(songsInFolder);

          foundPlaylists.add(
            Playlist(
              id: entity.path,
              name: folderName,
              folderPath: entity.path,
              songs: songsInFolder,
              author: 'Yoner Isaza',
            ),
          );
        }
      }

      // Also scan root directory directly for loose songs
      final looseSongs = await _scanSongsInDirectory(
        _rootMusicDirectory!,
        'General',
        artworkDir,
      );
      for (final s in looseSongs) {
        if (!foundAllSongs.any((existing) => existing.filePath == s.filePath)) {
          foundAllSongs.add(s);
        }
      }

      _playlists = foundPlaylists;
      _allSongs = foundAllSongs;
      _statusMessage = '';
    } catch (e) {
      debugPrint('Error scanning music library: $e');
      _statusMessage = 'Error al escanear: $e';
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  Future<List<Song>> _scanSongsInDirectory(
    Directory dir,
    String defaultCategory, [
    Directory? artworkDir,
  ]) async {
    final List<Song> songs = [];
    final validExtensions = [
      '.mp3',
      '.m4a',
      '.webm',
      '.wav',
      '.flac',
      '.aac',
      '.ogg',
    ];

    try {
      final files = dir.listSync();
      for (final file in files) {
        if (file is File) {
          final ext = file.path.toLowerCase().substring(
            file.path.lastIndexOf('.'),
          );
          if (validExtensions.contains(ext)) {
            final song = await _parseAudioFile(
              file,
              defaultCategory,
              artworkDir,
            );
            songs.add(song);
          }
        }
      }
    } catch (e) {
      debugPrint('Error reading files in ${dir.path}: $e');
    }
    return songs;
  }

  Future<Song> _parseAudioFile(
    File file,
    String category, [
    Directory? artworkDir,
  ]) async {
    final fileName = file.uri.pathSegments.last;
    // El nombre del archivo es el respaldo si la etiqueta no existe o viene
    // corrupta (los MP3 descargados a veces traen tags ilegibles).
    final fileTitle = MetadataTextFixer.titleFromFileName(fileName);
    String title = fileTitle;
    String artist = 'Artista desconocido';
    String album = category;
    Duration duration = const Duration(minutes: 3, seconds: 45);
    Uint8List? artwork;
    bool isExplicit =
        title.toLowerCase().contains('remix') ||
        title.toLowerCase().contains('malandro') ||
        title.toLowerCase().contains('shit') ||
        category.toLowerCase().contains('trap');

    try {
      final metadata = readMetadata(file, getImage: true);
      // Los tags ID3 UTF-16 big-endian llegan decodificados como chino
      // (mojibake). MetadataTextFixer los repara y valida el texto.
      final fixedTitle = MetadataTextFixer.cleanTitle(metadata.title);
      final fixedArtist = MetadataTextFixer.cleanTagText(metadata.artist);
      final fixedAlbum = MetadataTextFixer.cleanTagText(metadata.album);
      if (fixedTitle != null && fixedTitle.trim().isNotEmpty) {
        title = fixedTitle.trim();
      }
      if (fixedArtist != null && fixedArtist.trim().isNotEmpty) {
        artist = fixedArtist.trim();
      }
      if (fixedAlbum != null && fixedAlbum.trim().isNotEmpty) {
        album = fixedAlbum.trim();
      }
      if (metadata.duration != null && metadata.duration!.inSeconds > 0) {
        duration = metadata.duration!;
      }
      if (metadata.pictures.isNotEmpty) {
        artwork = metadata.pictures.first.bytes;
      }
    } catch (e) {
      // ID3 read fallback
    }

    if (artwork == null) {
      final baseWithoutExt = file.path.substring(0, file.path.lastIndexOf('.'));
      final coverFile = File('$baseWithoutExt.jpg');
      if (coverFile.existsSync()) {
        try {
          artwork = coverFile.readAsBytesSync();
        } catch (_) {}
      }
    }

    if (artwork == null && artworkDir != null) {
      final videoId = videoIdFromPath(file.path);
      if (videoId != null) {
        final privateCover = artworkFileFor(artworkDir, videoId);
        if (privateCover.existsSync()) {
          try {
            artwork = privateCover.readAsBytesSync();
          } catch (e) {
            debugPrint('Error leyendo carátula privada: $e');
          }
        }
      }
    }

    return Song(
      id: file.path,
      title: title,
      artist: artist,
      album: album,
      filePath: file.path,
      duration: duration,
      artworkBytes: artwork,
      isExplicit: isExplicit,
      category: category,
    );
  }

  void toggleFavorite(Song song) {
    song.isFavorite = !song.isFavorite;
    notifyListeners();
  }
}
