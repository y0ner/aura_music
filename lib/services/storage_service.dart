  List<String> get topArtists => _memo('topArtists', _computeTopArtists);

  List<String> _computeTopArtists() {
    final counts = <String, ({String display, int count})>{};
    for (final song in _allSongs) {
      if (!song.hasKnownArtist) continue;
      final seenInSong = <String>{};
      for (final rawCredit in MetadataTextFixer.splitArtists(song.artist)) {
        final trimmed = rawCredit.trim();
        if (trimmed.isEmpty || trimmed == Song.unknownArtist) continue;
        final key = trimmed.toLowerCase();
        if (!seenInSong.add(key)) continue;
        final current = counts[key];
        counts[key] = (
          display: current?.display ?? trimmed,
          count: (current?.count ?? 0) + 1,
        );
      }
    }

    final entries = counts.values.toList()
      ..sort((a, b) {
        final cmp = b.count.compareTo(a.count);
        if (cmp != 0) return cmp;
        return a.display.toLowerCase().compareTo(b.display.toLowerCase());
      });

    return entries.take(_maxTopArtists).map((e) => e.display).toList();
  }

  Playlist? artistMix(String artist) => _memo(
    ('artistMix', artist.trim().toLowerCase()),
    () => _computeArtistMix(artist),
  );

  Playlist? _computeArtistMix(String artist) {
    final trimmed = artist.trim();
    final target = trimmed.toLowerCase();
    if (target.isEmpty || target == Song.unknownArtist.toLowerCase()) {
      return null;
    }

    final songs = _allSongs.where((song) {
      if (!song.hasKnownArtist) return false;
      return MetadataTextFixer.splitArtists(song.artist).any(
        (credit) => credit.trim().toLowerCase() == target,
      );
    }).toList();

    if (songs.isEmpty) return null;
    return Playlist(
      id: 'auto_artist_$trimmed',
      name: 'Mix · $trimmed',
      folderPath: _rootMusicDirectory?.path ?? '',
      songs: songs,
      isAutoGenerated: true,
    );
  }
