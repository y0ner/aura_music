import 'dart:io';

import 'package:aura_music/models/playlist_model.dart';
import 'package:aura_music/screens/playlist_detail_screen.dart';
import 'package:aura_music/services/player_service.dart';
import 'package:aura_music/services/storage_service.dart';
import 'package:aura_music/theme/app_theme.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:provider/provider.dart';

Future<(Directory, Directory, MusicStorageService)> _setupStorage(
  WidgetTester tester,
) {
  return tester
      .runAsync(() async {
        final root = await Directory.systemTemp.createTemp('aura_pl_root_');
        final covers = await Directory.systemTemp.createTemp('aura_pl_cov_');

        final trapDir = Directory('${root.path}/Trap Malandro')..createSync();
        await File('${trapDir.path}/Coronamos.m4a').writeAsBytes([]);
        await File('${trapDir.path}/Hoy.m4a').writeAsBytes([]);

        final popDir = Directory('${root.path}/Synth Pop')..createSync();
        await File('${popDir.path}/Noche.m4a').writeAsBytes([]);

        final storage = MusicStorageService(
          artworkDirectory: () async => covers,
        );
        await storage.setCustomRootDirectory(root.path);
        return (root, covers, storage);
      })
      .then((value) => value!);
}

Future<void> _cleanupStorage(
  WidgetTester tester,
  Directory root,
  Directory covers,
  MusicStorageService storage,
  PlayerService player,
) {
  return tester
      .runAsync(() async {
        await player.stopAndClear();
        try {
          if (await root.exists()) await root.delete(recursive: true);
        } catch (e) {
          debugPrint('Error limpiando root temporal: $e');
        }
        try {
          if (await covers.exists()) await covers.delete(recursive: true);
        } catch (e) {
          debugPrint('Error limpiando covers temporal: $e');
        }
      })
      .then((_) {
        player.dispose();
        storage.dispose();
      });
}

void main() {
  testWidgets(
    'muestra título y tooltips Reproducir, Aleatorio y Añadir a la fila',
    (WidgetTester tester) async {
      final (root, covers, storage) = await _setupStorage(tester);
      final player = PlayerService();
      player.linuxProcessStarter = (exe, args) async {
        return Process.start('sleep', ['30']);
      };

      final playlist = storage.playlists.firstWhere(
        (p) => p.name == 'Trap Malandro',
      );

      try {
        await tester.pumpWidget(
          MaterialApp(
            theme: AppTheme.darkTheme,
            home: MultiProvider(
              providers: [
                ChangeNotifierProvider.value(value: storage),
                ChangeNotifierProvider.value(value: player),
              ],
              child: PlaylistDetailScreen(playlist: playlist),
            ),
          ),
        );
        await tester.pump();

        expect(find.text('Trap Malandro'), findsOneWidget);
        expect(find.text(playlist.subtitle), findsOneWidget);
        expect(find.byTooltip('Reproducir'), findsOneWidget);
        expect(find.byTooltip('Aleatorio'), findsOneWidget);
        expect(find.byTooltip('Añadir a la fila'), findsOneWidget);
        expect(find.byTooltip('Volver'), findsOneWidget);
        expect(find.byTooltip('Opciones de la playlist'), findsOneWidget);
        expect(find.text('Coronamos'), findsOneWidget);
        expect(find.text('Hoy'), findsOneWidget);
        expect(find.text('Artista desconocido'), findsNothing);

        await tester.runAsync(() async {
          await tester.tap(find.byTooltip('Añadir a la fila'));
          await Future<void>.delayed(const Duration(milliseconds: 100));
        });
        await tester.pump();
        expect(player.queue, hasLength(2));

        await tester.runAsync(() async {
          await tester.tap(find.byTooltip('Aleatorio'));
          await Future<void>.delayed(const Duration(milliseconds: 100));
        });
        await tester.pump();

        expect(player.isShuffle, isTrue);
        expect(player.currentSong, isNotNull);
        expect(tester.takeException(), isNull);
      } finally {
        await tester.pumpWidget(const SizedBox.shrink());
        await _cleanupStorage(tester, root, covers, storage, player);
      }
    },
  );

  testWidgets('la variante de Me gusta vacía muestra el estado vacío', (
    WidgetTester tester,
  ) async {
    final (root, covers, storage) = await _setupStorage(tester);
    final player = PlayerService();
    final emptyLiked = Playlist(
      id: 'liked_songs_auto',
      name: 'Música que te gustó',
      folderPath: '',
      songs: [],
      isAutoGenerated: true,
    );

    try {
      await tester.pumpWidget(
        MaterialApp(
          theme: AppTheme.darkTheme,
          home: MultiProvider(
            providers: [
              ChangeNotifierProvider.value(value: storage),
              ChangeNotifierProvider.value(value: player),
            ],
            child: PlaylistDetailScreen(playlist: emptyLiked),
          ),
        ),
      );
      await tester.pump();

      expect(find.text('Música que te gustó'), findsOneWidget);
      expect(find.text('0 canciones'), findsOneWidget);
      expect(
        find.text(
          'Lo que marques con Me gusta en Aura. Vive en tu dispositivo: sin cuenta y sin conexión.',
        ),
        findsOneWidget,
      );
      expect(find.byIcon(Icons.thumb_up_outlined), findsOneWidget);
      expect(
        find.text('Toca Me gusta en el reproductor para guardar canciones aquí'),
        findsOneWidget,
      );
      expect(find.byTooltip('Reproducir'), findsOneWidget);
      expect(find.byTooltip('Aleatorio'), findsOneWidget);
      expect(find.byTooltip('Añadir a la fila'), findsOneWidget);
      expect(tester.takeException(), isNull);
    } finally {
      await tester.pumpWidget(const SizedBox.shrink());
      await _cleanupStorage(tester, root, covers, storage, player);
    }
  });

  testWidgets('la variante de Me gusta con canciones filtra por carpeta', (
    WidgetTester tester,
  ) async {
    final (root, covers, storage) = await _setupStorage(tester);
    final player = PlayerService();
    for (final s in storage.allSongs) {
      storage.toggleFavorite(s);
    }
    final liked = storage.likedSongsPlaylist!;

    try {
      await tester.pumpWidget(
        MaterialApp(
          theme: AppTheme.darkTheme,
          home: MultiProvider(
            providers: [
              ChangeNotifierProvider.value(value: storage),
              ChangeNotifierProvider.value(value: player),
            ],
            child: PlaylistDetailScreen(playlist: liked),
          ),
        ),
      );
      await tester.pump();

      expect(find.text('3 canciones'), findsOneWidget);
      expect(find.text('Todas'), findsOneWidget);
      expect(find.text('Trap Malandro'), findsOneWidget);
      expect(find.text('Synth Pop'), findsOneWidget);
      expect(find.text('Coronamos'), findsOneWidget);
      expect(find.text('Noche'), findsOneWidget);

      await tester.tap(find.text('Synth Pop'));
      await tester.pumpAndSettle();

      expect(find.text('Noche'), findsOneWidget);
      expect(find.text('Coronamos'), findsNothing);
      expect(tester.takeException(), isNull);
    } finally {
      await tester.pumpWidget(const SizedBox.shrink());
      await _cleanupStorage(tester, root, covers, storage, player);
    }
  });
}
