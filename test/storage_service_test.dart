import 'dart:io';

import 'package:aura_music/models/playlist_model.dart';
import 'package:aura_music/models/song_model.dart';
import 'package:aura_music/services/library_state_store.dart';
import 'package:aura_music/services/storage_service.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  late Directory rootDir;
  late Directory stateDir;
  late Directory coversDir;

  setUp(() async {
    rootDir = await Directory.systemTemp.createTemp('storage_music_test');
    stateDir = await Directory.systemTemp.createTemp('storage_state_test');
    coversDir = await Directory.systemTemp.createTemp('storage_covers_test');
  });

  tearDown(() async {
    for (final dir in [rootDir, stateDir, coversDir]) {
      if (await dir.exists()) {
        await dir.delete(recursive: true);
      }
    }
  });

  MusicStorageService createStorage() {
    return MusicStorageService(
      artworkDirectory: () async => coversDir,
      stateStore: LibraryStateStore(directoryProvider: () async => stateDir),
    );
  }

  Future<File> createEmptyM4a(
    String subfolder,
    String fileName, {
    DateTime? modifiedAt,
  }) async {
    final folder = Directory('${rootDir.path}/$subfolder');
    await folder.create(recursive: true);
    final file = File('${folder.path}/$fileName');
    await file.writeAsBytes(const <int>[]);
    if (modifiedAt != null) {
      await file.setLastModified(modifiedAt);
    }
    return file;
  }

  test(
    'favoritos persisten entre instancias, listas derivadas respetan orden y límite, y parsea artista',
    () async {
      await createEmptyM4a(
        'Pop',
        'The Weeknd - Call Out My Name (Official Video) [abcdefghijk].m4a',
        modifiedAt: DateTime(2026, 1, 10, 12),
      );
      await createEmptyM4a(
        'Urbano',
        'Esto Es Así [12345678901].m4a',
        modifiedAt: DateTime(2026, 1, 12, 12),
      );
      await createEmptyM4a(
        'Urbano',
        'Maluma - Cuatro Babys (Official Video) ft. Trap Capos, Noriel [zz112233445].m4a',
        modifiedAt: DateTime(2026, 1, 11, 12),
      );

      final storage1 = createStorage();
      expect(storage1.autoPlaylist(AutoPlaylistKind.recentlyAdded), isNull);
      expect(storage1.autoPlaylist(AutoPlaylistKind.mostPlayed), isNull);
      expect(storage1.autoPlaylist(AutoPlaylistKind.recentlyPlayed), isNull);

      await storage1.setCustomRootDirectory(rootDir.path);
      expect(storage1.allSongs, hasLength(3));

      final weekndSong = storage1.allSongs.firstWhere(
        (s) => s.filePath.contains('abcdefghijk'),
      );
      expect(weekndSong.artist, 'The Weeknd');
      expect(weekndSong.title, 'Call Out My Name');

      // Favorito persiste al recrear MusicStorageService con otro store sobre el mismo directorio.
      await storage1.toggleFavorite(weekndSong);
      expect(weekndSong.isFavorite, isTrue);

      final storage2 = createStorage();
      await storage2.setCustomRootDirectory(rootDir.path);

      final reloadedWeeknd = storage2.allSongs.firstWhere(
        (s) => s.filePath.contains('abcdefghijk'),
      );
      expect(reloadedWeeknd.isFavorite, isTrue);
      expect(storage2.likedSongsPlaylist?.songs, hasLength(1));
      expect(storage2.likedSongsPlaylist?.subtitle, 'Autogenerada · 1 canción');

      // recentlyAdded ordena de más nueva a más vieja por fecha del archivo.
      expect(storage2.recentlyAdded.map((s) => s.title).toList(), [
        'Esto Es Así',
        'Cuatro Babys',
        'Call Out My Name',
      ]);

      // recentlyPlayed y mostPlayed respetan orden y desempate.
      final asiSong = storage2.allSongs.firstWhere(
        (s) => s.title == 'Esto Es Así',
      );
      final babysSong = storage2.allSongs.firstWhere(
        (s) => s.title == 'Cuatro Babys',
      );

      storage2.recordPlay(reloadedWeeknd);
      storage2.recordPlay(asiSong);
      storage2.recordPlay(babysSong);
      storage2.recordPlay(babysSong);
      storage2.recordPlay(asiSong);
      await storage2.stateStore.flush();

      // Orden de más reciente: asiSong (última), babysSong, reloadedWeeknd.
      expect(storage2.recentlyPlayed.map((s) => s.title).toList(), [
        'Esto Es Así',
        'Cuatro Babys',
        'Call Out My Name',
      ]);
      // Cuatro Babys y Esto Es Así empatan con 2; Esto Es Así fue más reciente.
      expect(storage2.mostPlayed.map((s) => s.title).toList(), [
        'Esto Es Así',
        'Cuatro Babys',
        'Call Out My Name',
      ]);

      final autoRecent = storage2.autoPlaylist(AutoPlaylistKind.recentlyAdded);
      expect(autoRecent?.id, 'auto_recently_added');
      expect(autoRecent?.name, 'Recién añadidas');
      expect(autoRecent?.isAutoGenerated, isTrue);
      expect(autoRecent?.subtitle, 'Autogenerada · 3 canciones');

      final autoMost = storage2.autoPlaylist(AutoPlaylistKind.mostPlayed);
      expect(autoMost?.id, 'auto_most_played');
      expect(autoMost?.name, 'Más escuchadas');

      final autoPlayed = storage2.autoPlaylist(AutoPlaylistKind.recentlyPlayed);
      expect(autoPlayed?.id, 'auto_recently_played');
      expect(autoPlayed?.name, 'Escuchado hace poco');

      // Búsqueda sin tildes ni mayúsculas, priorizando las que empiezan por la consulta.
      await createEmptyM4a('Pop', 'De Esto Nada [00000000009].m4a');
      await storage2.scanLibrary();
      expect(storage2.searchSongs('asi').map((s) => s.title), ['Esto Es Así']);
      expect(storage2.searchSongs('esto').map((s) => s.title).toList(), [
        'Esto Es Así',
        'De Esto Nada',
      ]);
      expect(storage2.searchSongs('weeknd').map((s) => s.title), [
        'Call Out My Name',
      ]);
      expect(storage2.searchSongs('   '), isEmpty);
      expect(storage2.searchSongs('desconocido'), isEmpty);

      // Búsqueda de playlists.
      expect(storage2.searchPlaylists('urb').map((p) => p.name), ['Urbano']);
      expect(storage2.searchPlaylists(''), isEmpty);

      // Artistas y mix por artista.
      expect(storage2.topArtists, isNotEmpty);
      final malumaMix = storage2.artistMix('maluma');
      expect(malumaMix?.id, 'auto_artist_maluma');
      expect(malumaMix?.name, 'Mix · maluma');
      expect(malumaMix?.songs.map((s) => s.title), ['Cuatro Babys']);
      expect(storage2.artistMix('Inexistente'), isNull);
    },
  );

  test(
    'búsquedas recientes delegan en el store, notifican y los subtítulos no usan emojis',
    () async {
      await createEmptyM4a('Favoritas', 'Esto Es Así.m4a');
      final storage = createStorage();
      await storage.setCustomRootDirectory(rootDir.path);

      var notifications = 0;
      storage.addListener(() => notifications++);

      await storage.addSearch('Esto Es Así');
      await storage.addSearch('Weeknd');
      expect(storage.recentSearches, ['Weeknd', 'Esto Es Así']);
      expect(notifications, 2);

      await storage.removeSearch('weeknd');
      expect(storage.recentSearches, ['Esto Es Así']);
      await storage.clearSearches();
      expect(storage.recentSearches, isEmpty);
      expect(notifications, 4);

      expect(storage.playlists.single.subtitle, 'Playlist · 1 canción');
      final bigPlaylist = Playlist(
        id: 'p2',
        name: 'Varias',
        folderPath: rootDir.path,
        songs: List.generate(
          12,
          (i) => Song(
            id: '$i',
            title: 'T$i',
            artist: Song.unknownArtist,
            album: 'A',
            filePath: '/$i.m4a',
            duration: const Duration(minutes: 2),
          ),
        ),
      );
      expect(bigPlaylist.subtitle, 'Playlist · 12 canciones');
    },
  );

  test(
    'listas derivadas se limitan a 20 canciones y topArtists a 10',
    () async {
      for (var i = 1; i <= 25; i++) {
        final padded = i.toString().padLeft(2, '0');
        await createEmptyM4a(
          'Todas',
          'Artista$padded - Canción $padded [id0000000$padded].m4a',
          modifiedAt: DateTime(2026, 2, i),
        );
      }
      final storage = createStorage();
      await storage.setCustomRootDirectory(rootDir.path);

      for (final song in storage.allSongs) {
        storage.recordPlay(song);
      }
      await storage.stateStore.flush();

      expect(storage.recentlyAdded, hasLength(20));
      expect(storage.recentlyPlayed, hasLength(20));
      expect(storage.mostPlayed, hasLength(20));
      expect(storage.topArtists, hasLength(10));
    },
  );

  test(
    'la misma canción en dos carpetas aparece una sola vez en las listas',
    () async {
      await createEmptyM4a('Trap', 'GALACTICOS [lsAr91prCBo].m4a');
      await createEmptyM4a('Urbano', 'GALACTICOS [lsAr91prCBo].m4a');
      final storage = createStorage();
      await storage.setCustomRootDirectory(rootDir.path);
      expect(storage.allSongs, hasLength(2));

      for (final song in storage.allSongs) {
        storage.recordPlay(song);
      }
      await storage.stateStore.flush();

      expect(storage.recentlyPlayed, hasLength(1));
      expect(storage.mostPlayed, hasLength(1));
      expect(storage.recentlyAdded, hasLength(1));
    },
  );

  test('las listas derivadas se recalculan tras cada cambio', () async {
    await createEmptyM4a('Pop', 'Uno [aaaaaaaaaaa].m4a');
    await createEmptyM4a('Pop', 'Dos [bbbbbbbbbbb].m4a');
    final storage = createStorage();
    await storage.setCustomRootDirectory(rootDir.path);

    expect(storage.recentlyPlayed, isEmpty);
    expect(identical(storage.topArtists, storage.topArtists), isTrue);

    storage.recordPlay(storage.allSongs.first);
    await storage.stateStore.flush();
    expect(storage.recentlyPlayed, hasLength(1));

    final liked = storage.allSongs.last;
    await storage.toggleFavorite(liked);
    expect(storage.likedSongsPlaylist!.songs, [liked]);
  });

  test('recupera una vez las carátulas que faltan y refresca la biblioteca',
      () async {
    await createEmptyM4a('Pop', 'Uno [aaaaaaaaaaa].m4a');
    await createEmptyM4a('Pop', 'Sin id.m4a');
    final calls = <Set<String>>[];
    final storage = MusicStorageService(
      artworkDirectory: () async => coversDir,
      stateStore: LibraryStateStore(directoryProvider: () async => stateDir),
      coverRecoverer: (dir, ids) async {
        calls.add(ids.toSet());
        await File('${dir.path}/aaaaaaaaaaa.jpg').writeAsBytes([1, 2, 3]);
        return 1;
      },
    );
    await storage.setCustomRootDirectory(rootDir.path);

    Song uno() => storage.allSongs.firstWhere((s) => s.title == 'Uno');
    for (var i = 0; i < 100 && uno().artworkBytes == null; i++) {
      await Future<void>.delayed(const Duration(milliseconds: 50));
    }

    expect(uno().artworkBytes, isNotNull);
    expect(calls, [
      {'aaaaaaaaaaa'},
    ]);
    // Otro escaneo en la misma sesión no vuelve a intentarlo.
    await storage.scanLibrary();
    expect(calls, hasLength(1));
  });
}
